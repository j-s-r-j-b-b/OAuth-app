/**
 * Summarise the library and its verification results as Markdown (written to docs/VERIFICATION.md).
 *   npm run report
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DIFFICULTY_INFO, Guide } from '../shared/schema.ts';

const guides = readdirSync('data/library')
  .filter((f) => f.endsWith('.json'))
  .map((f) => Guide.parse(JSON.parse(readFileSync(join('data/library', f), 'utf8'))))
  .sort((a, b) => a.verdict.timeToProduction.maxHours - b.verdict.timeToProduction.maxHours);

const managed = { available: 'managed', 'not-available': 'bring your own', 'not-in-catalog': 'not in catalog', unknown: '?' } as const;
/** Cut at a word boundary (never mid-word) and add an ellipsis. */
const clip = (text: string, max: number): string => {
  if (text.length <= max) return text;
  const end = /\s/.test(text[max]) ? max : text.lastIndexOf(' ', max);
  return text.slice(0, end > 0 ? end : max).replace(/[\s,;:.\-–—(]+$/, '') + '…';
};
const claims = (g: Guide) => [g.factors, g.requirements, g.scopes, g.blockers, g.nuances, g.phases.flatMap((p) => p.steps)].flat();

const out: string[] = [];
out.push('# Library summary and verification\n');
out.push('Generated by `npm run report` from `data/library/*.json`.\n');
out.push('## The library at a glance\n');
out.push('| App | Composio OAuth | Rating | First test connection | Any user can connect | Longest pole |');
out.push('|---|---|---|---|---|---|');
for (const g of guides) {
  const v = g.verdict;
  out.push(
    `| [${g.app.name}](../data/library/${g.slug}.json) | ${managed[g.composio.managedOAuth]} | ${DIFFICULTY_INFO[v.difficulty].label} | ${v.timeToFirstConnection.label} | ${v.timeToProduction.label} | ${clip(v.longestPole.replace(/\|/g, '/'), 140)} |`,
  );
}

out.push('\n## Evidence behind each guide\n');
out.push('| App | Claims | Tested | Official | Reported | Inferred | Sources | Probes | Open questions |');
out.push('|---|---|---|---|---|---|---|---|---|');
const tot = { claims: 0, tested: 0, official: 0, reported: 0, inferred: 0, sources: 0, probes: 0, open: 0 };
for (const g of guides) {
  const c = claims(g);
  const n = (k: string) => c.filter((x) => x.confidence === k).length;
  const row = { claims: c.length, tested: n('tested'), official: n('official'), reported: n('reported'), inferred: n('inferred'), sources: g.evidence.sources.length, probes: g.evidence.probes.length, open: g.evidence.openQuestions.length };
  for (const k of Object.keys(tot) as (keyof typeof tot)[]) tot[k] += row[k];
  out.push(`| ${g.app.name} | ${row.claims} | ${row.tested} | ${row.official} | ${row.reported} | ${row.inferred} | ${row.sources} | ${row.probes} | ${row.open} |`);
}
out.push(`| **Total** | **${tot.claims}** | **${tot.tested}** | **${tot.official}** | **${tot.reported}** | **${tot.inferred}** | **${tot.sources}** | **${tot.probes}** | **${tot.open}** |`);

const verified = guides.filter((g) => g.evidence.verification);
const items = verified.flatMap((g) => g.evidence.verification!.items.map((i) => ({ ...i, app: g.app.name })));
const count = (o: string) => items.filter((i) => i.outcome === o).length;
out.push('\n## Independent verification\n');
out.push(
  `${verified.length} of ${guides.length} guides were re-checked by a separate verifier agent (a different model with a fresh context and an adversarial brief). It re-read the cited sources for the most decision-critical claims and re-ran probes. **${items.length} claims checked: ${count('confirmed')} confirmed, ${count('corrected')} corrected (and fixed in the guide), ${count('unverifiable')} unverifiable.**\n`,
);
out.push('### What was corrected\n');
for (const i of items.filter((x) => x.outcome === 'corrected')) out.push(`- **${i.app}**: ${i.claim} — ${i.note}`);
out.push('\n### What could not be verified\n');
for (const i of items.filter((x) => x.outcome === 'unverifiable')) out.push(`- **${i.app}**: ${i.claim} — ${i.note}`);
out.push('\n### Open questions across the library\n');
for (const g of guides) for (const q of g.evidence.openQuestions) out.push(`- **${g.app.name}**: ${q.question}`);

writeFileSync('docs/VERIFICATION.md', out.join('\n') + '\n');
console.log(`Wrote docs/VERIFICATION.md: ${guides.length} guides, ${items.length} verification items (${count('confirmed')} confirmed, ${count('corrected')} corrected, ${count('unverifiable')} unverifiable).`);
