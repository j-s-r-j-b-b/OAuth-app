/**
 * Compare live-agent guides (docs/live-eval/*.json, produced with `npm run generate -- <app> --out docs/live-eval`)
 * against the verified library guides for the same Composio toolkit. Writes docs/LIVE_EVAL.md.
 *   npm run live-eval
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { QualityReport } from '../shared/events.ts';
import { DIFFICULTY_INFO, Guide } from '../shared/schema.ts';

const DIR = 'docs/live-eval';
const load = (p: string) => Guide.parse(JSON.parse(readFileSync(p, 'utf8')));
const library = readdirSync('data/library')
  .filter((f) => f.endsWith('.json'))
  .map((f) => load(join('data/library', f)));
const live = readdirSync(DIR)
  .filter((f) => f.endsWith('.json') && !f.endsWith('.trace.json'))
  .map((f) => ({ g: load(join(DIR, f)), q: (existsSync(join(DIR, f.replace('.json', '.trace.json'))) ? JSON.parse(readFileSync(join(DIR, f.replace('.json', '.trace.json')), 'utf8')).quality : null) as QualityReport | null }));

const overlap = (a: Guide['verdict']['timeToProduction'], b: Guide['verdict']['timeToProduction']) => a.minHours <= b.maxHours && b.minHours <= a.maxHours;
const out: string[] = ['# Live agent evaluation\n', 'Generated by `npm run live-eval`. Each live guide was produced by the live agent (`npm run generate -- <app> --out docs/live-eval`), on the free Gemini model with Composio Search, with no human edits.\n'];

out.push('## Run summary\n');
out.push('| App | Rating | First connection | Production | Claims (tested / official / reported / inferred) | Sources (read) | Probes passed | LLM calls | Time | Auto-fixes |');
out.push('|---|---|---|---|---|---|---|---|---|---|');
for (const { g, q } of live) {
  const v = g.verdict;
  const c = q?.claims;
  out.push(
    `| ${g.app.name} | ${DIFFICULTY_INFO[v.difficulty].label} | ${v.timeToFirstConnection.label} | ${v.timeToProduction.label} | ${c ? `${c.tested} / ${c.official} / ${c.reported} / ${c.inferred}` : '–'} | ${q ? `${q.sources.total} (${q.sources.fetched})` : '–'} | ${q ? `${q.probes.pass}/${q.probes.total}` : '–'} | ${q?.llm.calls ?? '–'} | ${g.meta.durationSec ?? '–'}s | ${q?.fixes.length ?? '–'} |`,
  );
}

out.push('\n## Against the verified library\n');
out.push('Where a verified library guide exists for the same toolkit, the live guide is compared with it on the decision-level outputs.\n');
out.push('| App | Rating (live → library) | Production (live vs library) | Ranges overlap | Factors agreeing (of 8) | Disagreements |');
out.push('|---|---|---|---|---|---|');
let compared = 0;
let ratingMatch = 0;
let rangeOverlap = 0;
let factorAgree = 0;
for (const { g } of live) {
  const lib = library.find((l) => l.composio.toolkitSlug && l.composio.toolkitSlug === g.composio.toolkitSlug);
  if (!lib) continue;
  compared++;
  const same = g.verdict.difficulty === lib.verdict.difficulty;
  if (same) ratingMatch++;
  const ov = overlap(g.verdict.timeToProduction, lib.verdict.timeToProduction);
  if (ov) rangeOverlap++;
  const diffs = lib.factors
    .map((lf) => ({ key: lf.key, lib: lf.value, live: g.factors.find((x) => x.key === lf.key)?.value ?? 'missing' }))
    .filter((d) => d.lib !== d.live);
  factorAgree += 8 - diffs.length;
  out.push(
    `| ${g.app.name} | ${DIFFICULTY_INFO[g.verdict.difficulty].label} → ${DIFFICULTY_INFO[lib.verdict.difficulty].label} ${same ? '✓' : '✗'} | ${g.verdict.timeToProduction.label} vs ${lib.verdict.timeToProduction.label} | ${ov ? '✓' : '✗'} | ${8 - diffs.length} | ${diffs.map((d) => `${d.key}: ${d.live} vs ${d.lib}`).join('; ') || '–'} |`,
  );
}
if (compared) {
  out.push(
    `\n**${compared} apps compared: rating matched ${ratingMatch}/${compared}, production ranges overlapped ${rangeOverlap}/${compared}, factors agreed ${factorAgree}/${compared * 8}.**\n`,
  );
  out.push('### Longest pole, side by side\n');
  for (const { g } of live) {
    const lib = library.find((l) => l.composio.toolkitSlug && l.composio.toolkitSlug === g.composio.toolkitSlug);
    if (!lib) continue;
    out.push(`- **${g.app.name}.** Live: ${g.verdict.longestPole}\n  Library: ${lib.verdict.longestPole}`);
  }
}
writeFileSync('docs/LIVE_EVAL.md', out.join('\n') + '\n');
console.log(out.join('\n'));
